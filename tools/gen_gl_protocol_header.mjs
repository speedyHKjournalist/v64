#!/usr/bin/env node
// Writes the guest's OpenGL protocol headers from
// src/browser/glbridge/gl-webgpu/gl_protocol.js:
//
//   node tools/gen_gl_protocol_header.mjs <retro-gaming-site>/glbridge/openglproxy
//
// gl_protocol.h: the protocol's constants, the GLFN opcodes and the fixed
// header of every hand-written record, with an assert of each header's size
// and of every field's offset. gl_opcode_names.h: the diagnostic DLL's opcode
// names. With no directory it prints gl_protocol.h.
import { createRequire as create_require } from "node:module";
import { writeFileSync as write_file_sync } from "node:fs";
import { join } from "node:path";

const require = create_require(import.meta.url);
const P = require("../src/browser/glbridge/gl-webgpu/gl_protocol.js");

const GENERATED = ["/* Generated by v86's tools/gen_gl_protocol_header.mjs from",
    " * src/browser/glbridge/gl-webgpu/gl_protocol.js -- edit that, not this. */"];

const literal = value => typeof value === "string" ? value :
    (value >= 0x100 ? "0x" + value.toString(16).toUpperCase() : String(value)) + "u";
// QUERY_ERROR -> V86GLRecordQueryError
const struct_name = name => "V86GLRecord" + name.toLowerCase().replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

function protocol_header() {
    const out = [...GENERATED, "#ifndef V86GL_PROTOCOL_H", "#define V86GL_PROTOCOL_H", "",
        "#include <stddef.h>", "#include <stdint.h>", ""];
    for(const [name, value, comment] of P.DEFINES) {
        if(comment) out.push("/* " + comment + " */");
        out.push("#define " + name + " " + literal(value));
    }
    out.push("", "/* The record opcodes; a flat record's payload is its argument list */", "enum {");
    const opcodes = P.OPCODES.map(([name, value]) => "    GLFN_" + name + " = " + value);
    out.push(opcodes.join(",\n"), "};", "#define V86GL_OPCODE_COUNT " + P.OPCODES.length + "u", "");
    out.push("/* The fixed header of each hand-written record; its data follows it */");
    for(const [name, record] of Object.entries(P.RECORDS)) {
        out.push("typedef struct " + struct_name(name) + " {");
        for(const [field, f] of Object.entries(record.fields))
            out.push("    " + P.C_TYPES[f.type] + " " + field + (f.count > 1 ? "[" + f.count + "]" : "") + ";");
        out.push("} " + struct_name(name) + ";");
    }
    out.push("", "/* The layout gl_protocol.js describes: every header's size and every field's offset */");
    for(const [name, record] of Object.entries(P.RECORDS)) {
        const s = struct_name(name);
        out.push("typedef char " + s + "Size[sizeof(" + s + ") == " + record.size + " ? 1 : -1];");
        for(const [field, f] of Object.entries(record.fields))
            out.push("typedef char " + s + "_" + field + "[offsetof(" + s + ", " + field + ") == " + f.offset +
                " ? 1 : -1];");
    }
    out.push("", "#endif", "");
    return out.join("\n");
}

function names_header() {
    const count = Math.max(...P.OPCODES.map(([, value]) => value)) + 1;
    const out = [...GENERATED, "#ifndef V86GL_OPCODE_NAMES_H", "#define V86GL_OPCODE_NAMES_H", "",
        "#define V86GL_OPCODE_NAME_COUNT " + count + "u",
        "static const char *const g_v86gl_opcode_names[V86GL_OPCODE_NAME_COUNT] = {",
        "    [0] = \"UNKNOWN\","];
    for(const [name, value] of [...P.OPCODES].sort((a, b) => a[1] - b[1]))
        out.push("    [" + value + "] = \"" + name + "\",");
    out.push("};", "",
        "static const char *v86gl_opcode_name(unsigned int opcode)", "{",
        "    if (opcode >= V86GL_OPCODE_NAME_COUNT ||", "            !g_v86gl_opcode_names[opcode])",
        "        return \"UNKNOWN\";", "    return g_v86gl_opcode_names[opcode];", "}", "", "#endif", "");
    return out.join("\n");
}

const dir = process.argv[2];
if(dir) {
    write_file_sync(join(dir, "gl_protocol.h"), protocol_header());
    write_file_sync(join(dir, "gl_opcode_names.h"), names_header());
}
else {
    process.stdout.write(protocol_header());
}
