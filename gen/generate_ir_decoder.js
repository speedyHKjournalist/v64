#!/usr/bin/env node
// Encoding facts come only from x86_table. Semantic coverage is deliberately separate.
import fs from "node:fs";
import assert from "node:assert/strict";
import table, {opcode_map, opcode_prefix, opcode_family as family_key} from "./x86_table.js";
import {lowering, loweringTests as lowering_tests} from "./ir_semantics.js";
const hex = n => n.toString(16).toUpperCase();
const family_modrm = new Map();
for(const e of table) if(!e.escape && !family_modrm.has(family_key(e.opcode))) family_modrm.set(family_key(e.opcode), !!e.e);
// (escapes: the decoders read the third opcode byte of 0F 38 and 0F 3A)
const source_rows = table.filter(e => !e.prefix && !e.escape);
// The interpreter group switch delivers #UD immediately for absent /g entries:
// ModRM has been fetched, but EA/immediate/task guards have not run.
const grouped = new Map();
for(const e of source_rows) if(e.fixed_g !== undefined) {
    if(!grouped.has(e.opcode)) grouped.set(e.opcode, new Set());
    grouped.get(e.opcode).add(e.fixed_g);
}
for(const [opcode, groups] of grouped) for(let fixed_g=0; fixed_g<8; fixed_g++) {
    if(!groups.has(fixed_g)) source_rows.push({opcode, fixed_g, group_ud:true, reg_ud:true, mem_ud:true, custom:true, block_boundary:true, no_next_instruction:true});
}
// Ids: key * 16 + group slot; the three-byte maps (whose keys are too wide
// for that) above 0x10000000, by map, prefix and opcode byte
const encoding_id = e => {
    const slot = e.fixed_g === undefined ? 0 : e.fixed_g + 1;
    const map = opcode_map(e.opcode);
    if(map !== "0F38" && map !== "0F3A") return e.opcode * 16 + slot;
    const prefix = {0: 0, 0x66: 1, 0xF2: 2, 0xF3: 3}[opcode_prefix(e.opcode)];
    return 0x10000000 + (((map === "0F3A") * 4 + prefix) * 256 + (e.opcode & 0xFF)) * 16 + slot;
};
// (sorted by key: the decoders binary-search the catalogue)
const rows = source_rows.filter(e => !e.prefix).map(e => ({...e,
    id: encoding_id(e),
    fetch_modrm: family_modrm.get(family_key(e.opcode)),
})).sort((a, b) => a.opcode - b.opcode || (a.fixed_g ?? -1) - (b.fixed_g ?? -1));
assert.equal(new Set(rows.map(e => e.id)).size, rows.length);
const bool = x => x ? "true" : "false";
const imm = e => e.imm8 ? "Byte" : e.imm8s ? "SignedByte" : e.imm16 ? "Word" :
    e.imm1632 ? "Operand" : e.immaddr ? "Address" : "None";
const flags = ["fetch_modrm", "group_ud", "task_switch_test", "custom", "e", "ignore_mod", "reg_ud", "mem_ud", "os", "block_boundary", "no_next_instruction",
    "absolute_jump", "jump_offset_imm", "conditional_jump", "custom_sti", "is_fpu", "sse", "is_string", "unimplemented"];
const refining = e => e.sse || e.refining === 1 ? "crate::decode_rules::REFINING_ALL" : e.refining === "rep" ? "crate::decode_rules::REFINING_REP" : "0";
const feature = e => e.feature ? "crate::cpu::features::" + e.feature.replace(".", "_") : "0";
let rust = "// Generated by gen/generate_ir_decoder.js. Do not edit.\nuse super::{Encoding, ImmediateKind};\n#[rustfmt::skip]\npub static ENCODINGS: &[Encoding] = &[\n";
for(const e of rows) {
    rust += `    Encoding { id: ${e.id}, opcode: 0x${hex(e.opcode)}, group: ${e.fixed_g ?? -1}, immediate: ImmediateKind::${imm(e)}, extra_bytes: ${e.extra_imm16 ? 2 : e.extra_imm8 ? 1 : 0}, refining: ${refining(e)}, feature: ${feature(e)}, ${flags.map(k => `${k}: ${bool(e[k])}`).join(", ")} },\n`;
}
rust += "];\n";
// Bounded binary search over a generated opcode-key index, followed by <= 8 group entries.
const buckets = new Map();
for(let i = 0; i < rows.length; i++) {
    const opcode = rows[i].opcode;
    if(!buckets.has(opcode)) buckets.set(opcode, [i, i]);
    buckets.get(opcode)[1] = i + 1;
}
rust += "pub static OPCODES: &[(u32, usize, usize)] = &[\n";
for(const [opcode, [start, end]] of buckets) rust += `    (0x${hex(opcode)}, ${start}, ${end}),\n`;
rust += "];\n";
const forms = [];
for(const e of rows) for(const operand_size of e.os ? [16, 32] : [null])
    for(const address_size of [16, 32]) for(const operand of e.e && !e.ignore_mod ? ["reg", "mem"] : [e.e ? "reg" : "implicit"]) {
        const invalid = e.group_ud || operand === "reg" && e.reg_ud || operand === "mem" && e.mem_ud;
        // (forms whose semantics come in a later phase of docs/simd-xsave-plan.md are #UD)
        forms.push({encoding_id: e.id, key: `${hex(e.opcode)}/${e.fixed_g ?? "-"}/${operand_size ?? "fixed"}/${address_size}/${operand}`,
            operand_size, address_size, operand,
            lowering: invalid || e.unimplemented ? "BaselineUD" : lowering(e, operand),
            tests: invalid ? ["tests/ir/decode/decode.rs", "tests/ir/semantics/invalid.rs", "tests/ir/differential/invalid.mjs"] :
                e.unimplemented ? ["tests/ir/decode/decode.rs", "tests/rust/decode_rules.mjs"] : lowering_tests(e, operand)});
    }
const coverage = {schema: 2, source: "gen/x86_table.js", encodings: rows.length, forms,
    note: "lowering is the IR compiler's path for each form (Pending: none attributed). Encoding forms are not a claim of semantic coverage. Prefix repetitions, mode guards and nested x87 subforms require additional tests."};
const coverage_text = JSON.stringify({...coverage, forms: undefined}, null, 2).slice(0, -2) +
    ',\n  "forms": [\n' + forms.map(f => "    " + JSON.stringify(f)).join(",\n") + "\n  ]\n}\n";
const outputs = [["src/rust/ir/frontend/encodings.rs", rust], ["src/rust/ir/frontend/ir-coverage.json", coverage_text]];
for(const [path, content] of outputs) {
    if(process.argv.includes("--check")) assert.equal(fs.readFileSync(path, "utf8"), content, `${path} is stale`);
    else fs.writeFileSync(path, content);
}
console.log(`IR catalogue: ${rows.length} encodings, ${forms.length} forms, ${forms.filter(f => f.lowering === "Pending").length} pending`);
