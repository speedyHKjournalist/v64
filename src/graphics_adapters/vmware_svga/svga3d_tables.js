/** @return {number} the vertices (or indices) n primitives of a D3DPRIMITIVETYPE take */
export function primitive_vertices(d3d_type, count)
{
    switch(d3d_type)
    {
        case 1: return count;
        case 2: return count * 2;
        case 3: return count + 1;
        case 4: return count * 3;
        default: return count + 2;
    }
}

/** SVGA3dTransformType -> D3DTRANSFORMSTATETYPE */
export function d3d_transform(type)
{
    if(type === C.SVGA3D_TRANSFORM_WORLD) return 256;
    if(type === C.SVGA3D_TRANSFORM_VIEW) return 2;
    if(type === C.SVGA3D_TRANSFORM_PROJECTION) return 3;
    if(type >= C.SVGA3D_TRANSFORM_TEXTURE0 && type <= C.SVGA3D_TRANSFORM_TEXTURE7) return 16 + type - C.SVGA3D_TRANSFORM_TEXTURE0;
    if(type >= C.SVGA3D_TRANSFORM_WORLD1 && type <= C.SVGA3D_TRANSFORM_WORLD3) return 257 + type - C.SVGA3D_TRANSFORM_WORLD1;
    return -1;
}

/** SVGA3dLightType -> D3DLIGHTTYPE (both spot models are D3D's one) */
export function d3d_light_type(type)
{
    return type === C.SVGA3D_LIGHTTYPE_POINT ? 1 : type === C.SVGA3D_LIGHTTYPE_DIRECTIONAL ? 3 : 2;
}

