/**
 * SVGA3dTextureArgData plus modifiers -> D3DTA_*: the sources are numbered
 * differently, and SVGA3D's ALPHA and ONE_MINUS bits are D3D's
 * ALPHAREPLICATE and COMPLEMENT the other way round
 */
export function d3d_texture_argument(value)
{
    const source = { [C.SVGA3D_TA_TFACTOR]: 3, [C.SVGA3D_TA_PREVIOUS]: 1, [C.SVGA3D_TA_DIFFUSE]: 0,
        [C.SVGA3D_TA_TEXTURE]: 2, [C.SVGA3D_TA_SPECULAR]: 4, [C.SVGA3D_TA_CONSTANT]: 6 }[value & 0xF];
    return (source === undefined ? 1 : source) |
        (value & C.SVGA3D_TM_ALPHA ? 0x20 : 0) | (value & C.SVGA3D_TM_ONE_MINUS ? 0x10 : 0);
}

/** SVGA3dTexTransformFlags -> D3DTEXTURETRANSFORMFLAGS: a coordinate count */
export function d3d_texture_transform_flags(value)
{
    const count = (value & 1) + (value >> 1 & 1) + (value >> 2 & 1) + (value >> 3 & 1);
    return count | (value & C.SVGA3D_TEX_PROJECTED ? 256 : 0);
}

/** SVGA3D_TEX_ADDRESS_EDGE is D3D's clamp; the rest are numbered alike */
export function d3d_address(value)
{
    return value === C.SVGA3D_TEX_ADDRESS_EDGE ? 3 : value;
}

